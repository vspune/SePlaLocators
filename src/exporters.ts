import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { config } from "./config.js";
import { frameworkDisagreements } from "./validators.js";
import type { DiscoveredElement, LocatorCandidate, LocatorInventory } from "./types.js";

type Framework = "playwright" | "selenium";

/**
 * Collision-free folder name: host + full path + hash route.
 *   https://www.example.com/            -> www-example-com
 *   https://app.example.com/admin/list  -> app-example-com_admin_list
 *   https://app.example.com/#/dashboard -> app-example-com_dashboard
 */
export function pageFolderName(url: string): string {
  const parsed = new URL(url);
  const clean = (value: string) => value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  const host = clean(parsed.host) || "page";
  const parts = parsed.pathname.split("/").map(clean).filter(Boolean);
  const hashRoute = /^#!?\//.test(parsed.hash) ? parsed.hash.replace(/^#!?/, "").split("?")[0].split("/").map(clean).filter(Boolean) : [];
  const name = [host, ...parts, ...hashRoute].join("_");
  if (name.length <= 120) return name;
  const digest = createHash("sha1").update(url).digest("hex").slice(0, 8);
  return `${name.slice(0, 110)}_${digest}`;
}

function statusOf(c: LocatorCandidate, fw: Framework) { return fw === "playwright" ? c.playwrightStatus : c.seleniumStatus; }
function countOf(c: LocatorCandidate, fw: Framework) { return fw === "playwright" ? c.playwrightCount : c.seleniumCount; }

/** Best candidate that matched exactly one element in this framework, or undefined. Never falls back to a non-unique one. */
export function bestUniqueCandidate(element: DiscoveredElement, fw: Framework): LocatorCandidate | undefined {
  const unique = element.candidates.filter(c => statusOf(c, fw) === "unique");
  const other: Framework = fw === "playwright" ? "selenium" : "playwright";
  return unique.sort((a, b) =>
    a.rank - b.rank ||
    // Prefer one that is also unique in the other framework (portable across both suites).
    Number(statusOf(b, other) === "unique") - Number(statusOf(a, other) === "unique") ||
    (a.kind === b.kind ? 0 : a.kind === "css" ? -1 : 1) ||
    a.selector.length - b.selector.length
  )[0];
}

function isIdentifier(key: string): boolean {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key);
}

function describe(element: DiscoveredElement): string {
  const name = element.label?.text || element.text || element.attributes["aria-label"] || element.attributes.placeholder || "";
  const what = `${element.tagName}${element.elementType ? `[type=${element.elementType}]` : ""}`;
  const safe = name.replace(/[\r\n\u2028\u2029]+/g, " ").slice(0, 50).replace(/\*\//g, "* /");
  return safe ? `${what} "${safe}"` : what;
}

function commentFor(element: DiscoveredElement, chosen: LocatorCandidate): string {
  const counts = `PW ${chosen.playwrightCount ?? "-"} / SE ${chosen.seleniumCount ?? "-"}`;
  const flags = [
    chosen.stability === "fragile" ? `⚠ fragile: ${chosen.note ?? chosen.strategy}` : chosen.note,
    element.visibleAtScan ? undefined : "hidden at scan time"
  ].filter(Boolean).join("; ");
  return `  /** ${describe(element)} · ${chosen.strategy} · ${chosen.stability} · ${counts}${flags ? ` · ${flags}` : ""} */`;
}

function header(inventory: LocatorInventory, fw: Framework, included: number): string {
  const skipped = inventory.elements.length - included;
  return [
    `// Generated by LocatorFinder from ${inventory.pageUrl} at ${inventory.scannedAt}.`,
    `// Only locators that matched exactly ONE element in ${fw === "playwright" ? "Playwright" : "Selenium"} are included (${included} of ${inventory.elements.length}).`,
    skipped > 0 ? `// ${skipped} element(s) had no unique locator: see review.md. Review "fragile" entries before relying on them.` : `// Review "fragile" entries before relying on them.`
  ].join("\n");
}

export function renderPlaywright(inventory: LocatorInventory): { source: string; included: number } {
  const lines: string[] = [];
  for (const element of inventory.elements) {
    const chosen = bestUniqueCandidate(element, "playwright");
    if (!chosen) continue;
    const key = isIdentifier(element.key) ? element.key : JSON.stringify(element.key);
    lines.push(commentFor(element, chosen));
    lines.push(`  ${key}: ${JSON.stringify(`${chosen.kind}=${chosen.selector}`)},`);
  }
  const included = lines.length / 2;
  const source = `${header(inventory, "playwright", included)}

export const playwrightLocators = {
${lines.join("\n")}
} as const;

export type PlaywrightLocatorKey = keyof typeof playwrightLocators;
`;
  return { source, included };
}

export function renderSelenium(inventory: LocatorInventory): { source: string; included: number } {
  const lines: string[] = [];
  for (const element of inventory.elements) {
    const chosen = bestUniqueCandidate(element, "selenium");
    if (!chosen) continue;
    const key = isIdentifier(element.key) ? element.key : JSON.stringify(element.key);
    lines.push(commentFor(element, chosen));
    lines.push(`  ${key}: By.${chosen.kind}(${JSON.stringify(chosen.selector)}),`);
  }
  const included = lines.length / 2;
  const source = `${header(inventory, "selenium", included)}
import { By } from "selenium-webdriver";

export const seleniumLocators = {
${lines.join("\n")}
} satisfies Record<string, By>;

export type SeleniumLocatorKey = keyof typeof seleniumLocators;
`;
  return { source, included };
}

function mdEscape(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/`/g, "'").replace(/\n/g, " ");
}

export function renderReview(inventory: LocatorInventory): string {
  const noneInEither: DiscoveredElement[] = [];
  const onlyOne: { element: DiscoveredElement; missing: Framework }[] = [];
  const fragileOnly: { element: DiscoveredElement; candidate: LocatorCandidate }[] = [];

  for (const element of inventory.elements) {
    const pw = bestUniqueCandidate(element, "playwright");
    const se = bestUniqueCandidate(element, "selenium");
    if (!pw && !se) noneInEither.push(element);
    else if (!pw) onlyOne.push({ element, missing: "playwright" });
    else if (!se && inventory.selenium.status === "ok") onlyOne.push({ element, missing: "selenium" });
    const chosen = pw ?? se;
    if (chosen && chosen.stability === "fragile") fragileOnly.push({ element, candidate: chosen });
  }

  const disagreements = frameworkDisagreements(inventory);
  const out: string[] = [];
  out.push(`# Locator review: ${inventory.pageTitle || inventory.pageUrl}`, "");
  out.push(`- Page: ${inventory.pageUrl}`, `- Scanned: ${inventory.scannedAt}`);
  out.push(`- Elements scanned: ${inventory.elements.length} of ${inventory.totalElements}${inventory.truncated ? " (truncated)" : ""}`);
  out.push(`- Playwright validation: ${inventory.playwright.status}${inventory.playwright.message ? ` (${inventory.playwright.message})` : ""}`);
  out.push(`- Selenium validation: ${inventory.selenium.status}${inventory.selenium.message ? ` (${inventory.selenium.message})` : ""}`);
  out.push(`- Redacted attribute values: ${inventory.stats.redactedAttributeValues}; URLs with query string removed: ${inventory.stats.strippedUrls}`, "");

  if (inventory.warnings.length > 0) {
    out.push("## Scan warnings", "", ...inventory.warnings.map(w => `- ${w}`), "");
  }

  out.push(`## No unique locator (${noneInEither.length})`, "");
  if (noneInEither.length === 0) out.push("None.", "");
  else {
    out.push("These elements are NOT in the generated locator files. Ask developers for a test id, or locate them relative to a nearby element.", "");
    out.push("| Key | Element | Best candidate tried | PW / SE matches |", "|---|---|---|---|");
    for (const element of noneInEither) {
      const best = [...element.candidates].sort((a, b) => a.rank - b.rank)[0];
      out.push(`| ${element.key} | ${mdEscape(describe(element))} | \`${mdEscape(best?.selector ?? "-")}\` | ${best?.playwrightCount ?? "-"} / ${best?.seleniumCount ?? "-"} |`);
    }
    out.push("");
  }

  if (onlyOne.length > 0) {
    out.push(`## Unique in only one framework (${onlyOne.length})`, "", "| Key | Element | Missing from |", "|---|---|---|");
    for (const { element, missing } of onlyOne) out.push(`| ${element.key} | ${mdEscape(describe(element))} | ${missing} |`);
    out.push("");
  }

  out.push(`## Only a fragile locator available (${fragileOnly.length})`, "");
  if (fragileOnly.length === 0) out.push("None.", "");
  else {
    out.push("| Key | Element | Locator | Why fragile |", "|---|---|---|---|");
    for (const { element, candidate } of fragileOnly) {
      out.push(`| ${element.key} | ${mdEscape(describe(element))} | \`${mdEscape(candidate.selector)}\` | ${mdEscape(candidate.note ?? candidate.strategy)} |`);
    }
    out.push("");
  }

  out.push(`## Playwright vs Selenium count differences (${disagreements.length})`, "");
  if (disagreements.length === 0) out.push("None.", "");
  else {
    out.push("Different counts usually mean the two sessions saw different page state (login, timing, open menus) or that Playwright CSS reached into shadow DOM.", "");
    out.push("| Key | Selector | Playwright | Selenium |", "|---|---|---|---|");
    for (const { key, candidate } of disagreements.slice(0, 100)) {
      out.push(`| ${key} | \`${mdEscape(candidate.selector)}\` | ${candidate.playwrightCount} | ${candidate.seleniumCount} |`);
    }
    if (disagreements.length > 100) out.push("", `…and ${disagreements.length - 100} more (see locator-inventory.json).`);
    out.push("");
  }
  return out.join("\n");
}

export interface SaveResult {
  folder: string;
  playwrightIncluded: number;
  seleniumIncluded: number;
}

export async function saveInventory(inventory: LocatorInventory): Promise<SaveResult> {
  const folder = path.join(config.locatorsDir, pageFolderName(inventory.pageUrl));
  await mkdir(folder, { recursive: true });

  const pw = renderPlaywright(inventory);
  const se = renderSelenium(inventory);
  await writeFile(path.join(folder, "locator-inventory.json"), JSON.stringify(inventory, null, 2), "utf8");
  await writeFile(path.join(folder, "playwright.locators.ts"), pw.source, "utf8");
  await writeFile(path.join(folder, "selenium.locators.ts"), se.source, "utf8");
  await writeFile(path.join(folder, "review.md"), renderReview(inventory), "utf8");

  return { folder, playwrightIncluded: pw.included, seleniumIncluded: se.included };
}
